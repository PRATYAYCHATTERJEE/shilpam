function renderCraftCategories(category) {

    const container =
        document.getElementById("categoryProducts");

    const title =
        document.getElementById("categorySectionTitle");

    if (!container) return;

    const data =
        craftCategories[category];

    if (!data) return;

    title.textContent = data.title;


    container.innerHTML = data.cards.map(card => {

        return `
    <article class="craft-category-card">

        <div class="craft-category-image">

            <img
                src="${card.image}"
                alt="${card.name}"
                loading="lazy"
            >

        </div>

        <div class="craft-category-info">

            <h3>
                ${card.name}
            </h3>

            <div class="craft-category-bottom">

                <span class="craft-category-price">
                    ${card.price}
                </span>

                <span class="craft-category-explore">
                    Explore →
                </span>

            </div>

        </div>

    </article>
`;

    }).join("");
}



function initializeCraftTabs() {

    const tabs =
        document.querySelectorAll(".craft-tab");

    tabs.forEach(tab => {

        tab.addEventListener("click", () => {

            const category =
                tab.dataset.category;

            if (!craftCategories[category]) {
                return;
            }


            /* Active tab */

            tabs.forEach(item => {
                item.classList.remove("active");
            });

            tab.classList.add("active");


            /* Change lower content */

            renderCraftCategories(category);

        });

    });

}


document.addEventListener("DOMContentLoaded", () => {

    renderCraftCategories("all");

    initializeCraftTabs();

});